import { test, expect, type Page } from "@playwright/test";
import { randomUUID } from "node:crypto";

async function onboard(page: Page) {
  const email = `financial-${randomUUID()}@example.test`;
  const signup = await page.request.post("http://127.0.0.1:9099/identitytoolkit.googleapis.com/v1/accounts:signUp?key=demo-public-key", { data: { email, password: "LocalTestPassword123!", returnSecureToken: true } });
  const headers = { Origin: "http://127.0.0.1:3100", "X-DukaanPilot-Request": "1", "Idempotency-Key": randomUUID() };
  expect((await page.request.post("/api/v1/auth/session", { headers, data: { idToken: (await signup.json()).idToken } })).status()).toBe(200);
  expect((await page.request.post("/api/v1/businesses", { headers: { ...headers, "Idempotency-Key": randomUUID() }, data: { name: "Synthetic financial shop", businessType: "Retail", city: "Karachi" } })).status()).toBe(201);
  const response = await page.request.post("/api/v1/customers", { headers: { ...headers, "Idempotency-Key": randomUUID() }, data: { name: "Ali Financial", phoneE164: "03051234567" } });
  expect(response.status()).toBe(201);
  return (await response.json()).data as { id: string };
}

test("financial previews, partial repayment, orders and export work on the owner dashboard", async ({ page }, testInfo) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  const customer = await onboard(page);
  expect((await page.request.get("/health/ready")).status()).toBe(200);
  await page.goto("/ledger");
  await page.getByRole("button", { name: "Record sale", exact: true }).click();
  await page.getByLabel("Customer", { exact: true }).selectOption(customer.id);
  await page.getByLabel("Sale total (PKR)", { exact: true }).fill("650");
  await page.getByLabel("Repayment due date and time (Pakistan)", { exact: false }).fill("2026-12-01T15:00");
  await page.getByRole("button", { name: "Create preview", exact: true }).click();
  await expect(page.getByRole("region", { name: "Action preview", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Create WhatsApp approval command", exact: true })).toHaveCount(0);
  await expect(page.getByRole("region", { name: "Action preview", exact: true })).toContainText(new Intl.DateTimeFormat("en-PK", { timeZone: "Asia/Karachi", dateStyle: "medium", timeStyle: "short" }).format(new Date("2026-12-01T10:00:00Z")));
  const before = (await (await page.request.get("/api/v1/dashboard")).json()).data;
  expect(before.outstandingPaisa).toBe("0");
  const approvalResponse = page.waitForResponse(response => response.request().method() === "POST" && response.url().endsWith("/approve"));
  await page.getByRole("button", { name: "Approve and save", exact: true }).click();
  expect((await approvalResponse).status()).toBe(200);
  await expect(page.getByText("Approved and saved once.", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Record payment", exact: true }).click();
  await page.getByLabel("Customer", { exact: true }).selectOption(customer.id);
  await page.getByLabel("Payment amount (PKR)", { exact: true }).fill("200");
  await page.getByRole("button", { name: "Create preview", exact: true }).click();
  await expect(page.getByRole("region", { name: "Action preview", exact: true })).toContainText("Rs 450.00");
  await page.getByRole("button", { name: "Approve and save", exact: true }).click();
  await expect(page.getByRole("region", { name: "Action preview", exact: true })).toHaveCount(0);
  await page.getByLabel("View customer ledger", { exact: true }).selectOption(customer.id);
  await expect(page.locator(".ledger-balance")).toContainText("Rs 450.00");
  const downloadEvent = page.waitForEvent("download");
  await page.getByRole("link", { name: "Export ledger CSV", exact: true }).click();
  expect((await downloadEvent).suggestedFilename()).toMatch(/^dukaanpilot-ledger-.*\.csv$/);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: `work/screenshots/s3-ledger-${testInfo.project.name}.png`, fullPage: true });
  await page.goto("/orders");
  await page.getByRole("button", { name: "New order preview", exact: true }).click();
  await page.getByLabel("Customer", { exact: true }).selectOption(customer.id);
  await page.getByLabel("Item 1 description", { exact: true }).fill("Cake");
  await page.getByLabel("Item 1 unit price (PKR)", { exact: true }).fill("2500");
  const due = new Date(Date.now() + 86400000 + 5 * 3600000).toISOString().slice(0, 16);
  await page.getByLabel("Due date and time (Pakistan)", { exact: true }).fill(due);
  await page.getByRole("button", { name: "Create preview", exact: true }).click();
  await page.getByRole("button", { name: "Approve and save", exact: true }).click();
  await expect(page.getByRole("button", { name: "Mark fulfilled", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Enable bounded follow-up", exact: true }).click();
  await expect(page.getByRole("region", { name: "Order follow-ups", exact: true })).toContainText("SCHEDULED");
  await page.getByRole("button", { name: "Mark fulfilled", exact: true }).click();
  await page.getByRole("button", { name: "Approve and save", exact: true }).click();
  await expect(page.getByRole("button", { name: "Create sale preview", exact: true })).toBeVisible();
  await expect(page.getByRole("region", { name: "Order follow-ups", exact: true })).toContainText("RESOLVED");
  const after = (await (await page.request.get("/api/v1/dashboard")).json()).data;
  expect(after.salesPaisa).toBe("65000"); expect(after.collectionsPaisa).toBe("20000");
  await page.goto("/");
  await expect(page.getByRole("heading", { name: "Today’s summary", exact: true })).toBeVisible();
  await expect(page.locator(".daily-summary")).toContainText("Rs 450.00");
  expect(errors).toEqual([]);
});
